use std::path::Path;

use eframe::egui;
use tracing::Level;
use tracing_appender::non_blocking::WorkerGuard;
use tracing_appender::rolling::{RollingFileAppender, Rotation};

fn main() -> eframe::Result {
    let _guard = init_logging(&paths::AppDirs::system().logs);
    tracing::info!(version = env!("CARGO_PKG_VERSION"), "VoiceChanger starting");
    if self_test::requested(std::env::args()) {
        // No window: the installer test reads the exit code and stdout.
        let code = match self_test::run(&vc_engine::assets::candidates()) {
            Ok(report) => {
                tracing::info!("{report}");
                println!("{report}");
                0
            }
            Err(e) => {
                tracing::error!("self-test failed: {e}");
                println!("self-test failed: {e}");
                1
            }
        };
        drop(_guard);
        std::process::exit(code);
    }
    let instance = match instance::acquire(instance::APP_NAME) {
        Ok(instance::Instance::Primary(primary)) => Some(primary),
        Ok(instance::Instance::Secondary) => {
            tracing::info!("VoiceChanger is already running: asked it to show its window");
            return Ok(());
        }
        Err(e) => {
            tracing::warn!("single-instance check failed: {e}");
            None
        }
    };
    let dirs = paths::AppDirs::system();
    let (config, note) = config::load(&dirs.settings_file());
    let options = eframe::NativeOptions {
        viewport: egui::ViewportBuilder::default()
            .with_title(app::window_title())
            .with_inner_size([720.0, 520.0])
            .with_min_inner_size([520.0, 400.0])
            .with_icon(app_icon()),
        ..Default::default()
    };
    let startup = app::Startup {
        dirs,
        config,
        notes: note.into_iter().collect(),
        instance,
    };
    eframe::run_native(
        &app::window_title(),
        options,
        Box::new(|cc| Ok(Box::new(app::VcApp::new(cc, startup)))),
    )
}

/// The app logo, generated by `cargo xtask gen-icon`: the window, taskbar and tray icons.
const ICON_PNG: &[u8] = include_bytes!("../../../assets/icon-256.png");

/// The window and taskbar icon.
fn app_icon() -> egui::IconData {
    eframe::icon_data::from_png_bytes(ICON_PNG).expect("assets/icon-256.png is a valid PNG")
}

/// Logs to daily files in `dir` (seven kept), and to stderr in debug builds.
/// Falls back to stderr only when the folder or the file can't be set up.
/// Keep the guard alive until exit so buffered lines are flushed.
fn init_logging(dir: &Path) -> Option<WorkerGuard> {
    let appender = std::fs::create_dir_all(dir)
        .map_err(|e| e.to_string())
        .and_then(|()| {
            RollingFileAppender::builder()
                .rotation(Rotation::DAILY)
                .filename_prefix("voicechanger.log")
                .max_log_files(7)
                .build(dir)
                .map_err(|e| e.to_string())
        });
    let appender = match appender {
        Ok(appender) => appender,
        Err(e) => {
            tracing_subscriber::fmt()
                .with_max_level(Level::INFO)
                .with_writer(std::io::stderr)
                .init();
            tracing::warn!(dir = %dir.display(), "log files disabled: {e}");
            return None;
        }
    };
    let (file, guard) = tracing_appender::non_blocking(appender);
    #[cfg(debug_assertions)]
    let writer = {
        use tracing_subscriber::fmt::writer::MakeWriterExt;
        file.and(std::io::stderr)
    };
    #[cfg(not(debug_assertions))]
    let writer = file;
    tracing_subscriber::fmt()
        .with_max_level(Level::INFO)
        .with_ansi(false)
        .with_writer(writer)
        .init();
    Some(guard)
}

